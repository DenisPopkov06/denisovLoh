"""Земляной холмик у надгробия — часть МОДЕЛИ надгробия (gravestone_*.glb), а не зоны.

Так надгробие и закопанная земля — одна сущность: куда игра поставит (или переставит) камень, туда уедет и холмик;
в модели зоны и на карте земли холмиков нет. Форму использует grave_mound_props.py (геометрия в .glb).

Холмик — вытянутый покатый горб от надгробия вперёд (в сторону «лица»): камень отставлен назад от выкопанной
области — цоколь стоит на траве, земля начинается у его лицевого края и плавно поднимается к голове холмика; к ногам
холмик сужается и скругляется, у самого края плавно сходит на нет (без стенки). Один размер на все надгробия и их
варианты (целое / разбитое / наклонённое): при смене состояния модель подменяется, холмик остаётся тем же.

Локальные координаты — как у надгробия: u — вперёд от его центра (в сторону «лица»), v — вправо, метры.
"""
import numpy as np

U_BACK = 0.14         # ближний к камню край: у лицевой грани цоколя (0.15–0.21 м) — цоколь на траве, земля начинается у его края
U_HEAD = 0.34         # отсюда вперёд холмик во всю ширину и высоту
U_FOOT = 2.54         # дальний край у «ног»
BACK_ROUND = U_HEAD - U_BACK
FOOT_ROUND = 0.60     # последние 0.6 м сужаются скруглением
HALF_W = 0.58         # полуширина у головы (шире любого цоколя: 0.72–0.86 м)
FOOT_W = 0.78         # полуширина у ног — доля от полуширины у головы
H_HEAD = 0.14         # высота гребня у головы (м), от неё вся форма считается; к ногам ниже на 40 %
H_TAPER = 0.40
EMBED = 0.014         # на столько вся поверхность утоплена в землю: край холмика уходит под плоскость земли


def _back(u):
    """Задний край: 1 → 0 на BACK_ROUND метров от U_HEAD к U_BACK (квадрат эллипса — плавный взлёт земли у камня)."""
    kb = np.clip((U_HEAD - np.asarray(u, float)) / BACK_ROUND, 0.0, 1.0)
    return 1 - kb ** 2


def _foot(u):
    """Ноги: 1 → 0 на FOOT_ROUND метров, скругление эллипсом."""
    kf = np.clip((np.asarray(u, float) - (U_FOOT - FOOT_ROUND)) / FOOT_ROUND, 0.0, 1.0)
    return np.sqrt(np.clip(1 - kf ** 2, 0, 1))


def _inside(u):
    u = np.asarray(u, float)
    return (u > U_BACK) & (u < U_FOOT)


def half_width(u, wh=HALF_W):
    """Полуширина холмика на расстоянии u от центра надгробия; wh — полуширина у головы."""
    u = np.asarray(u, float)
    t = np.clip((u - U_HEAD) / (U_FOOT - U_HEAD), 0.0, 1.0)
    return wh * (1 - (1 - FOOT_W) * t ** 1.2) * np.sqrt(np.clip(_back(u), 0, 1)) * _foot(u) * _inside(u)


def height(u, v, wh=HALF_W):
    """Высота поверхности холмика над землёй (м), без утопления EMBED; 0 вне холмика."""
    u, v = np.asarray(u, float), np.asarray(v, float)
    w = half_width(u, wh)
    rr = np.clip(_back(u), 0, 1) * _foot(u) ** 0.8 * _inside(u)       # земля у камня сходит на нет без стенки
    r = np.where(w > 1e-6, np.abs(v) / np.maximum(w, 1e-6), 1.0)
    t = np.clip((u - U_HEAD) / (U_FOOT - U_HEAD), 0.0, 1.0)
    p = 2.4 + 2.6 * (1 - t) ** 1.5                                  # у головы плоский верх (закрывает цоколь), к ногам круглее
    cross = np.clip(1 - r ** p, 0.0, 1.0) ** 1.2                    # нулевой наклон у края — мягкий переход в землю
    return H_HEAD * (1 - H_TAPER * t) * cross * rr


def surface_z(u, v, wh=HALF_W):
    """Высота над плоскостью земли с утоплением: >0 только там, где холмик реально торчит из земли."""
    return np.maximum(height(u, v, wh) - EMBED, 0.0)
